/* The scales built into the FM-1 test firmware, as one MTS1 library in a C header (const: it stays in flash).
 * node tools/gen_device_scales.js → device/firmware/src/micro/scales_lib.h */
'use strict';
const fs = require('fs'), path = require('path'), C = require('./scl-codec.js');
const W = require('./world_scales.js');
const S = W.SCALES.map(f => ({ name: f.name, text: f.text }));
/* the page's built-in scales: the same list (tools/build_site.py inlines it) */
fs.writeFileSync(path.join(__dirname, '..', 'site', 'scales.json'), JSON.stringify(S));
const lib = C.buildLibrary(S);
if (lib.errors.length) throw new Error(JSON.stringify(lib.errors));
/* keep the order above (the library sorts by degrees): an index of positions in the sorted file */
const order = S.map(f => lib.scales.findIndex(s => s.file === f.name));
if (order.some(i => i < 0)) throw new Error('a scale went missing');
const hex = Array.from(lib.bytes, b => '0x' + b.toString(16).padStart(2, '0'));
const rows = []; for (let i = 0; i < hex.length; i += 16) rows.push('    ' + hex.slice(i, i + 16).join(', ') + ',');
const out = `/* Generated by tools/gen_device_scales.js: do not edit. ${lib.scales.length} scales, ${lib.bytes.length} bytes, MTS1. */
#pragma once
#include <stdint.h>
#define LIB_SCALES ${lib.scales.length}u
static const uint8_t LIB[${lib.bytes.length}] = {
${rows.join('\n')}
};
static const uint8_t LIB_ORDER[${order.length}] = {${order.join(', ')}};   /* the scales in the order of the list */
`;
fs.writeFileSync(path.join(__dirname, '..', 'device', 'firmware', 'src', 'micro', 'scales_lib.h'), out);
console.log(`scales_lib.h: ${lib.scales.length} scales, ${lib.bytes.length} bytes`);
