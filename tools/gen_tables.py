#!/usr/bin/env python3
"""Computes the engine's constant tables on the computer (the FM-1 has no FPU) → engine/tables.h"""
import math, os, sys

FS = 44100
CTRL = 16                     # control rate: one tick every 16 frames
TICKS = FS / CTRL

out = []
def table(ctype, name, values, per_line=8, comment=''):
    if comment:
        out.append(f'/* {comment} */')
    out.append(f'static const {ctype} {name}[{len(values)}] = {{')
    for i in range(0, len(values), per_line):
        out.append('    ' + ', '.join(str(v) for v in values[i:i + per_line]) + ',')
    out.append('};')

# 2^(i/256), i = 0..256, Q30 (2^30 .. 2^31): one octave of pitch, linear interpolation in between
table('uint32_t', 'EXP2_Q30', [min(0xFFFFFFFF, round(2 ** (i / 256) * 2 ** 30)) for i in range(257)],
      comment='2^(i/256) in Q30, i = 0..256')

# phase increment per centi-hertz, as K / 2^24: inc = f * 2^32 / FS  =  (f_cHz * K) >> 24
K = round(2 ** (32 + 24) / (FS * 100))
out.append(f'#define INC_PER_CHZ_Q24 {K}ull  /* (f in 0.01 Hz) * this >> 24 = 32-bit phase increment */')

# sine, Q15, 1024 points + 1 for interpolation
table('int16_t', 'SINE_Q15', [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)], 16,
      comment='sin, Q15, 1024 + 1 points')

# filter: one-pole coefficient g = 1 - exp(-2 pi f / FS), Q16, f = 8.1758 Hz * 2^(c/1200) for c = 64 * i
F0 = 440 * 2 ** (-69 / 12)
g = []
for i in range(257):
    f = min(F0 * 2 ** (64 * i / 1200), FS * 0.45)
    g.append(round((1 - math.exp(-2 * math.pi * f / FS)) * 65536))
table('uint32_t', 'FILT_G_Q16', g, comment='ladder pole g, Q16, cutoff = 8.18 Hz * 2^(64 i / 1200) cents')
out.append('#define FILT_CENTS_STEP 64')
out.append(f'#define FILT_CENTS_MAX {64 * 256}')

# the drums' noise filter (a zero-delay-feedback state variable filter): g = tan(pi f / FS), Q16, same cents grid
tg = []
for i in range(257):
    f = min(F0 * 2 ** (64 * i / 1200), 18000)
    tg.append(round(math.tan(math.pi * f / FS) * 65536))
table('uint32_t', 'SVF_G_Q16', tg, comment='tan(pi f / FS), Q16, f = 8.18 Hz * 2^(64 i / 1200), at most 18 kHz')

# times: raw 0..16383 → 1 ms .. 20 s (exponential); a one-pole coefficient per control tick, Q30
def time_s(r): return 0.001 * (20000 ** (r / 16383))
coef = []
for i in range(257):
    t = time_s(i * 64)
    tau = t / 3.0                       # ~95 % of the way in the stated time
    coef.append(min(2 ** 30, round((1 - math.exp(-1 / (tau * TICKS))) * 2 ** 30)))
table('int32_t', 'TIME_COEF_Q30', coef, comment='one-pole coefficient per control tick, Q30, raw = 64 i')

# LFO rate: raw 0..16383 → 0.02 .. 40 Hz; phase increment per control tick
def rate_hz(r): return 0.02 * (2000 ** (r / 16383))
table('uint32_t', 'LFO_INC', [round(rate_hz(i * 64) * CTRL / FS * 2 ** 32) for i in range(257)],
      comment='LFO phase increment per control tick, raw = 64 i')

hdr = os.path.join(os.path.dirname(__file__), '..', 'engine', 'tables.h')
with open(hdr, 'w') as fh:
    fh.write('/* Generated by tools/gen_tables.py: do not edit. */\n#pragma once\n#include <stdint.h>\n\n')
    fh.write('\n'.join(out) + '\n')
print('wrote', os.path.normpath(hdr))
